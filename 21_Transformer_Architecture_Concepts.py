# Day 20 - Transformer Architecture Concepts

# Why Transformers were created
print("=== Why Transformers? ===")
print("RNN problem: processes words one by one, slow, forgets long sequences")
print("Transformer solution: processes all words in parallel using attention")

# Transformer advantages
print("\n=== Advantages ===")
print("1. Parallel processing - much faster than RNN")
print("2. Handles long range dependencies better")
print("3. Scalable - works for text, image, audio")
print("4. Foundation of BERT, GPT, T5, DALL-E")

# Transformer disadvantages  
print("\n=== Disadvantages ===")
print("1. Needs huge amounts of data")
print("2. Very expensive to train")
print("3. High memory requirement")

# Timeline
print("\n=== Timeline ===")
print("2017 - Attention is All You Need paper")
print("2018 - BERT by Google")
print("2019 - GPT-2 by OpenAI")
print("2020 - GPT-3 by OpenAI")
print("2022 - ChatGPT by OpenAI")